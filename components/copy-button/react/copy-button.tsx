"use client";

import { type ButtonHTMLAttributes, type MouseEvent, useRef, useState } from "react";
import { cn } from "../../lib/cn";

export interface CopyButtonProps
	extends Omit<ButtonHTMLAttributes<HTMLButtonElement>, "children" | "type"> {
	text: string;
	label?: string;
	copiedLabel?: string;
	iconOnly?: boolean;
}

export function CopyButton({
	text,
	label = "Copy",
	copiedLabel = "Copied",
	iconOnly = false,
	className,
	onClick,
	...rest
}: CopyButtonProps) {
	const [copied, setCopied] = useState(false);
	const [failed, setFailed] = useState(false);
	const timer = useRef<ReturnType<typeof setTimeout>>(undefined);

	async function copy() {
		clearTimeout(timer.current);
		try {
			await navigator.clipboard.writeText(text);
			setCopied(true);
			setFailed(false);
		} catch {
			// Clipboard access is denied outside a secure context; say so rather than lying.
			setFailed(true);
		}
		timer.current = setTimeout(() => {
			setCopied(false);
			setFailed(false);
		}, 1600);
	}

	return (
		<button
			data-slot="copy-button"
			data-state={copied ? "copied" : "idle"}
			{...rest}
			type="button"
			onClick={(event: MouseEvent<HTMLButtonElement>) => {
				copy();
				onClick?.(event);
			}}
			aria-label={iconOnly ? (copied ? copiedLabel : label) : undefined}
			className={cn(
				"inline-flex h-8 shrink-0 items-center gap-1.5 rounded-lg bg-card font-medium text-muted-foreground text-xs transition-[color,transform,scale,translate] duration-[var(--duration-press)] ease-[var(--ease-ui-out)] outline-none hover:bg-foreground/[0.06] hover:text-foreground focus-visible:ring-2 focus-visible:ring-ring active:scale-[var(--press-scale)] disabled:pointer-events-none disabled:opacity-50 motion-reduce:transition-none motion-reduce:active:scale-100",
				iconOnly ? "w-8 justify-center" : "px-2.5",
				className,
			)}
		>
			{copied ? (
				<svg viewBox="0 0 24 24" aria-hidden className="size-4">
					<g fill="currentColor">
						<path d="M16.207 10.5449C16.4927 10.2452 16.9677 10.2339 17.2676 10.5195C17.5673 10.8052 17.5786 11.2802 17.293 11.5801L12.6504 16.4551C12.5089 16.6036 12.3125 16.6874 12.1074 16.6875C11.9023 16.6875 11.706 16.6035 11.5645 16.4551L9.70703 14.5049C9.42141 14.205 9.43262 13.73 9.73242 13.4443C10.0324 13.1587 10.5073 13.1708 10.793 13.4707L12.1064 14.8496L16.207 10.5449Z" />
						<path
							fillRule="evenodd"
							clipRule="evenodd"
							d="M15 1.25C16.8724 1.25 18.4236 2.62236 18.7041 4.41602C19.4682 4.55408 20.1205 4.81774 20.6514 5.34863C21.2533 5.95055 21.5128 6.70829 21.6338 7.6084C21.7519 8.4869 21.75 9.60709 21.75 11V16C21.75 17.3929 21.7519 18.5131 21.6338 19.3916C21.5128 20.2917 21.2533 21.0494 20.6514 21.6514C20.0494 22.2533 19.2917 22.5128 18.3916 22.6338C17.5131 22.7519 16.3929 22.75 15 22.75H12C10.6071 22.75 9.4869 22.7519 8.6084 22.6338C7.70829 22.5128 6.95055 22.2533 6.34863 21.6514C5.81774 21.1205 5.55408 20.4682 5.41602 19.7041C3.62236 19.4236 2.25 17.8724 2.25 16V10C2.25 8.13558 2.24859 6.66159 2.40332 5.51074C2.56096 4.33844 2.89329 3.38991 3.6416 2.6416C4.38991 1.89329 5.33844 1.56096 6.51074 1.40332C7.66159 1.24859 9.13558 1.25 11 1.25H15ZM12 5.75C10.5648 5.75 9.5639 5.75202 8.80859 5.85352C8.07482 5.95217 7.68594 6.13242 7.40918 6.40918C7.13242 6.68594 6.95217 7.07482 6.85352 7.80859C6.75202 8.5639 6.75 9.56485 6.75 11V16C6.75 17.4352 6.75202 18.4361 6.85352 19.1914C6.95217 19.9252 7.13242 20.3141 7.40918 20.5908C7.68594 20.8676 8.07482 21.0478 8.80859 21.1465C9.5639 21.248 10.5648 21.25 12 21.25H15C16.4352 21.25 17.4361 21.248 18.1914 21.1465C18.9252 21.0478 19.3141 20.8676 19.5908 20.5908C19.8676 20.3141 20.0478 19.9252 20.1465 19.1914C20.248 18.4361 20.25 17.4352 20.25 16V11C20.25 9.56485 20.248 8.5639 20.1465 7.80859C20.0478 7.07482 19.8676 6.68594 19.5908 6.40918C19.3141 6.13242 18.9252 5.95217 18.1914 5.85352C17.4361 5.75202 16.4352 5.75 15 5.75H12ZM11 2.75C9.09324 2.75 7.73859 2.7515 6.71094 2.88965C5.70485 3.02491 5.12536 3.27894 4.70215 3.70215C4.27894 4.12536 4.02491 4.70485 3.88965 5.71094C3.7515 6.73859 3.75 8.09324 3.75 10V16C3.75 16.9873 4.38694 17.8229 5.27148 18.126C5.24999 17.5025 5.25 16.7957 5.25 16V11C5.25 9.60709 5.24812 8.4869 5.36621 7.6084C5.48723 6.70829 5.74672 5.95055 6.34863 5.34863C6.95055 4.74672 7.70829 4.48723 8.6084 4.36621C9.4869 4.24812 10.6071 4.25 12 4.25H15C15.7957 4.25 16.5025 4.24999 17.126 4.27148C16.8229 3.38694 15.9873 2.75 15 2.75H11Z"
						/>
					</g>
				</svg>
			) : (
				<svg viewBox="0 0 24 24" aria-hidden className="size-4">
					<path
						fill="currentColor"
						fillRule="evenodd"
						clipRule="evenodd"
						d="M15 1.25H10.9436C9.10583 1.24998 7.65019 1.24997 6.51098 1.40314C5.33856 1.56076 4.38961 1.89288 3.64124 2.64124C2.89288 3.38961 2.56076 4.33856 2.40314 5.51098C2.24997 6.65019 2.24998 8.10582 2.25 9.94357V16C2.25 17.8722 3.62205 19.424 5.41551 19.7047C5.55348 20.4687 5.81753 21.1208 6.34835 21.6517C6.95027 22.2536 7.70814 22.5125 8.60825 22.6335C9.47522 22.75 10.5775 22.75 11.9451 22.75H15.0549C16.4225 22.75 17.5248 22.75 18.3918 22.6335C19.2919 22.5125 20.0497 22.2536 20.6517 21.6517C21.2536 21.0497 21.5125 20.2919 21.6335 19.3918C21.75 18.5248 21.75 17.4225 21.75 16.0549V10.9451C21.75 9.57754 21.75 8.47522 21.6335 7.60825C21.5125 6.70814 21.2536 5.95027 20.6517 5.34835C20.1208 4.81753 19.4687 4.55348 18.7047 4.41551C18.424 2.62205 16.8722 1.25 15 1.25ZM17.1293 4.27117C16.8265 3.38623 15.9876 2.75 15 2.75H11C9.09318 2.75 7.73851 2.75159 6.71085 2.88976C5.70476 3.02502 5.12511 3.27869 4.7019 3.7019C4.27869 4.12511 4.02502 4.70476 3.88976 5.71085C3.75159 6.73851 3.75 8.09318 3.75 10V16C3.75 16.9876 4.38624 17.8265 5.27117 18.1293C5.24998 17.5194 5.24999 16.8297 5.25 16.0549V10.9451C5.24998 9.57754 5.24996 8.47522 5.36652 7.60825C5.48754 6.70814 5.74643 5.95027 6.34835 5.34835C6.95027 4.74643 7.70814 4.48754 8.60825 4.36652C9.47522 4.24996 10.5775 4.24998 11.9451 4.25H15.0549C15.8297 4.24999 16.5194 4.24998 17.1293 4.27117ZM7.40901 6.40901C7.68577 6.13225 8.07435 5.9518 8.80812 5.85315C9.56347 5.75159 10.5646 5.75 12 5.75H15C16.4354 5.75 17.4365 5.75159 18.1919 5.85315C18.9257 5.9518 19.3142 6.13225 19.591 6.40901C19.8678 6.68577 20.0482 7.07435 20.1469 7.80812C20.2484 8.56347 20.25 9.56458 20.25 11V16C20.25 17.4354 20.2484 18.4365 20.1469 19.1919C20.0482 19.9257 19.8678 20.3142 19.591 20.591C19.3142 20.8678 18.9257 21.0482 18.1919 21.1469C17.4365 21.2484 16.4354 21.25 15 21.25H12C10.5646 21.25 9.56347 21.2484 8.80812 21.1469C8.07435 21.0482 7.68577 20.8678 7.40901 20.591C7.13225 20.3142 6.9518 19.9257 6.85315 19.1919C6.75159 18.4365 6.75 17.4354 6.75 16V11C6.75 9.56458 6.75159 8.56347 6.85315 7.80812C6.9518 7.07435 7.13225 6.68577 7.40901 6.40901Z"
					/>
				</svg>
			)}
			{!iconOnly ? (failed ? "Press Ctrl+C" : copied ? copiedLabel : label) : null}
			<span role="status" className="sr-only">
				{copied ? copiedLabel : ""}
			</span>
		</button>
	);
}
